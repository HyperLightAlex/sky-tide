#!/usr/bin/env python3
"""Build Skytide's island art from the sheets in art/island-sheets and write
src/world/islandArt.js, which the game reads.

    python3 tools/bg/build_islands.py

- Ground (island-1-ground.png) and rock (island-2-rock.png): each of the six squares made to
  repeat (the cut join of tools/bg/build_painted.py) and packed back into a 3x2 sheet; the game
  loads the twelve squares as one texture array (render/islandsView.js).
- Far islands (island-4-far.png): each island cut out of the magenta by its own outline and
  packed into an atlas in the sheet's cell order, with where its ground's rim is (the widest row
  of its upper part), so a card can stand where its island is.
- Docks (island-3-docks.png) is not built: nothing in the game has a dock to put it on yet.

Run it again after replacing a sheet.
"""
import json
import os

import numpy as np
from PIL import Image
from scipy import ndimage

import build_painted as bp

ROOT = bp.ROOT
SHEETS = os.path.join(ROOT, 'art', 'island-sheets')
OUT = os.path.join(ROOT, 'assets', 'painted', 'islands')
MODULE = os.path.join(ROOT, 'src', 'world', 'islandArt.js')

GROUND = ['meadow', 'turf', 'flowers', 'path', 'earth', 'mossStone']
ROCK = ['layered', 'weathered', 'roots', 'crystal', 'crumble', 'hangingMoss']
FAR = ['meadow', 'spire', 'arch', 'waterfall', 'trees', 'tower']


def load(name):
    return np.asarray(Image.open(os.path.join(SHEETS, name)).convert('RGB')).astype(np.float32) / 255


def tiles(name):
    sheet = load(name)
    out = np.zeros((1024, 1536, 3), np.float32)
    for i in range(6):
        r, c = divmod(i, 3)
        out[r * 512:(r + 1) * 512, c * 512:(c + 1) * 512] = bp.seamless(sheet[r * 512:(r + 1) * 512, c * 512:(c + 1) * 512])
    return out


def far_cards(name):
    rgba = bp.keyed(load(name))
    lab, n = ndimage.label(rgba[..., 3] > 0.5)
    sizes = ndimage.sum(np.ones(lab.shape), lab, range(1, n + 1))
    cents = ndimage.center_of_mass(np.ones(lab.shape), lab, range(1, n + 1))
    H, W = lab.shape
    cell_of = {}
    for i, (cy, cx) in enumerate(cents):
        if sizes[i] < 30:
            continue
        cell_of.setdefault(int(cy // (H / 2)) * 3 + int(cx // (W / 3)), []).append(i + 1)
    atlas = np.zeros((1024, 1536, 4), np.float32)
    cards = []
    for cell in range(6):
        m = np.isin(lab, cell_of.get(cell, []))
        m = ndimage.binary_dilation(m, iterations=3)
        ys, xs = np.nonzero(m)
        y0, y1, x0, x1 = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1
        card = rgba[y0:y1, x0:x1].copy()
        card[..., 3] *= m[y0:y1, x0:x1]
        h, w = card.shape[:2]
        s = min(1.0, 500 / w, 500 / h)
        if s < 1:
            im = Image.fromarray((card * 255).astype(np.uint8), 'RGBA').resize((max(1, int(w * s)), max(1, int(h * s))), Image.LANCZOS)
            card = np.asarray(im).astype(np.float32) / 255
            h, w = card.shape[:2]
        # The ground's rim: the widest row in the card's upper two thirds (below it hangs the rock).
        widths = (card[..., 3] > 0.5).sum(1)
        top = int(h * 0.67)
        rim = int(np.argmax(widths[:top]))
        r, c = divmod(cell, 3)
        ox, oy = c * 512 + (512 - w) // 2, r * 512 + (512 - h) // 2
        atlas[oy:oy + h, ox:ox + w] = card
        cards.append(dict(name=FAR[cell], u0=ox / 1536, v0=1 - (oy + h) / 1024, u1=(ox + w) / 1536, v1=1 - oy / 1024,
                          aspect=round(w / h, 4), rimV=round(1 - (rim + 0.5) / h, 4), rimW=round(float(widths[rim]) / w, 4)))
    _, (iy, ix) = ndimage.distance_transform_edt(atlas[..., 3] < 0.02, return_indices=True)
    atlas[..., :3] = np.where(atlas[..., 3:] >= 0.02, atlas[..., :3], atlas[iy, ix, :3])
    return atlas, cards


def main():
    os.makedirs(OUT, exist_ok=True)
    rel = lambda f: f'assets/painted/islands/{f}'
    art = {}
    for key, sheet, names in [('ground', 'island-1-ground.png', GROUND), ('rock', 'island-2-rock.png', ROCK)]:
        if not os.path.exists(os.path.join(SHEETS, sheet)):
            print(f'{key}: not built (missing {sheet})')
            continue
        bp.save(tiles(sheet), os.path.join(OUT, f'{key}.webp'), 88)
        art[key] = dict(sheet=rel(f'{key}.webp'), tiles=names)
        print(f'{key}: built')
    if os.path.exists(os.path.join(SHEETS, 'island-4-far.png')):
        atlas, cards = far_cards('island-4-far.png')
        bp.save(atlas, os.path.join(OUT, 'far.webp'))
        art['far'] = dict(atlas=rel('far.webp'), cards=cards)
        print(f'far: built ({len(cards)} cards)')
    js = ('// Generated by tools/bg/build_islands.py. Do not edit by hand.\n'
          '// The islands\' painted art: the ground and rock squares (each a 3x2 sheet of repeating\n'
          '// 512 px squares, in the order of `tiles`), and the far islands\' cards (rectangle in the\n'
          '// atlas, v from the bottom; width over height; rimV, how far up the card the ground\'s rim\n'
          '// is, and rimW, how much of its width the rim spans).\n'
          'export const ISLAND_ART = %s;\n') % json.dumps(art, separators=(',', ':'))
    with open(MODULE, 'w') as fh:
        fh.write(js)
    print('wrote', os.path.relpath(MODULE, ROOT))


if __name__ == '__main__':
    main()
