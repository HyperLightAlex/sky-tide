def profile(img, c):
    W, H = img.size
    a = img.getchannel('A')
    x0, x1 = int(c['u0'] * W), int(c['u1'] * W)
    y0, y1 = int((1 - c['v1']) * H), int((1 - c['v0']) * H)   # image rows, top to bottom
    cw, ch = x1 - x0, y1 - y0
    px = a.load()
    rows = []
    for i in range(ROWS):
        # bottom to top
        y = y1 - 1 - int((i + 0.5) / ROWS * ch)
        left = right = None
        for x in range(x0, x1):
            if px[x, y] > 127:
                if left is None:
                    left = x
                right = x
        if left is None:
            rows.append((0.0, 0.0))
        else:
            hw = (right - left + 1) / 2 / cw
            cx = ((left + right + 1) / 2 - (x0 + cw / 2)) / cw
            rows.append((round(hw, 4), round(cx, 4)))
    return rows


def main():
    out = {}
    for name, (path, cards) in SETS.items():
        img = Image.open(os.path.join(ROOT, path)).convert('RGBA')
        sets = []
        for c in cards:
            rows = profile(img, c)
            sets.append({**c, 'hw': [r[0] for r in rows], 'cx': [r[1] for r in rows]})
        out[name] = {'url': path, 'cards': sets}
    js = ('// Generated by tools/clouds/build_cards.py from assets/painted. Do not edit by hand.\n'
          '// Each painted cloud card: its rectangle in its atlas (u0 v0 u1 v1, v from the bottom),\n'
          '// width over height, and its silhouette bottom to top in %d rows: the half-width (hw) and\n'
          '// the centre (cx), both as fractions of the card\'s width.\n'
          'export const CLOUD_CARDS = %s;\n') % (ROWS, json.dumps(out, separators=(',', ':')))
    open(os.path.join(ROOT, 'src/world/cloudCards.js'), 'w').write(js)
    for n, s in out.items():
        print(n, len(s['cards']), [round(max(c['hw']), 2) for c in s['cards']])


if __name__ == '__main__':
    main()
